export function parseLevel(levelText: string): EducationLevel {
  if (levelText.includes('ประถม')) return 'primary';
  if (levelText.includes('ตอนต้น') || levelText.includes('ม.ต้น')) return 'junior_high';
  return 'senior_high';
}

